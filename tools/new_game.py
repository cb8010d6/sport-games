"""Scaffold a new game module: game/scenes/<id>/ plus a test, ready for `--demo=2` and smoke_game.py.

    python tools/new_game.py table_tennis --name 乒乓球 --en "Table Tennis"
    python tools/new_game.py table_tennis --remove     # delete what the scaffold created

The manifest starts hidden (ready = false): the game runs with `-- --game=<id> --demo=2` and the
smoke checks cover it, but menus, solo and party leave it out until docs/NEW_GAME.md is done.
Afterwards run `godot --headless --path game --import` once so Godot writes the .gd.uid files.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GAME = ROOT / "game"
EN = GAME / "i18n/en.json"
ID = re.compile(r"[a-z][a-z0-9_]{1,19}")
DESC = "倾斜手柄左右移动方块，跟住发光的目标得分。（模板项目，玩法待实现）1–4 人分屏。"
DESC_EN = "Tilt the controller to move your block and stay on the glowing target to score. (Template game.) 1-4 players, split screen."

GAME_GD = '''extends RSPartyGame
## {name} ({id}): generated by tools/new_game.py. Placeholder play, replace it: each player
## tilts (roll) to move a block left and right and scores while it stays on a moving target.
## Every player has their own lane, split screen. Rules live in {id}_rules.gd, the HUD in
## {id}_hud.gd; the menu text, lessons and solo goals in {id}_module.tres.

const Rules := preload("res://scenes/{id}/{id}_rules.gd")
const Hud := preload("res://scenes/{id}/{id}_hud.gd")
const LANE_SPACING := 6.0


class Runner:
	var block: MeshInstance3D
	var target: MeshInstance3D
	var x := 0.0
	var lane_x := 0.0
	var bonus := 0.0             ## seconds of the current on-target streak


var _lobby_t := 0.0


func _module() -> RSGameModule:
	return RSCatalog.module(game_id(), true)


func _game_name() -> String:
	return tr(_module().name)


func _oled_name() -> String:
	return _module().oled


func _how_to_play() -> String:
	return tr(_module().desc)


func _runner(p: Player) -> Runner:
	return p.data


# --------------------------------------------------------------------------- world ----

func _setup_world() -> void:
	var env := Environment.new()
	env.background_mode = Environment.BG_COLOR
	env.background_color = Color(0.55, 0.7, 0.9)
	env.ambient_light_source = Environment.AMBIENT_SOURCE_COLOR
	env.ambient_light_color = Color(0.7, 0.75, 0.85)
	var world := WorldEnvironment.new()
	world.environment = env
	add_child(world)
	var sun := DirectionalLight3D.new()
	sun.rotation_degrees = Vector3(-50, -30, 0)
	add_child(sun)
	var ground := MeshInstance3D.new()
	var plane := PlaneMesh.new()
	plane.size = Vector2(60, 60)
	ground.mesh = plane
	ground.material_override = RSMeshUtil.toon_material(Color(0.3, 0.5, 0.35), 0.2, 0.9)
	add_child(ground)
	lobby_cam.position = Vector3(0, 9, 16)
	lobby_cam.look_at(Vector3.ZERO)


func _lobby_process(delta: float) -> void:
	_lobby_t += delta
	lobby_cam.position = Vector3(sin(_lobby_t * 0.2) * 4.0, 9, 16)
	lobby_cam.look_at(Vector3.ZERO)


# ------------------------------------------------------------------------- players ----

func _player_added(p: Player) -> void:
	var s := Runner.new()
	p.data = s
	s.lane_x = (p.c.player - 2.5) * LANE_SPACING
	s.block = _make_box(Vector3(1, 1, 1), color_of(p))
	s.target = _make_box(Vector3(Rules.TARGET_WIDTH, 0.1, 1.4), Color(1.0, 0.9, 0.3))
	p.cam.position = Vector3(s.lane_x, 4, 7)
	p.cam.look_at(Vector3(s.lane_x, 0, 0))
	_place(p, 0.0)


func _player_removed(p: Player) -> void:
	_runner(p).block.queue_free()
	_runner(p).target.queue_free()


func _make_box(size: Vector3, color: Color) -> MeshInstance3D:
	var node := MeshInstance3D.new()
	var mesh := BoxMesh.new()
	mesh.size = size
	node.mesh = mesh
	node.material_override = RSMeshUtil.toon_material(color, 0.2, 0.6)
	add_child(node)
	return node


func _place(p: Player, t: float) -> void:
	var s := _runner(p)
	s.block.position = Vector3(s.lane_x + s.x, 0.5, 0)
	s.target.position = Vector3(s.lane_x + Rules.target_x(t, p.c.player), 0.05, 0)


# ---------------------------------------------------------------------------- round ----

func _round_started(list: Array) -> void:
	for p: Player in list:
		p.score = 0
		_runner(p).x = 0.0
		_runner(p).bonus = 0.0
		_place(p, 0.0)


func _play_process(delta: float) -> void:
	for p: Player in ordered():
		var s := _runner(p)
		var goal := Rules.target_x(phase_time, p.c.player)
		var steer := 0.0
		if p.fake:
			steer = clampf((goal - s.x) * 0.8 + randf_range(-1.0, 1.0) * bot_error(), -1.0, 1.0)
		elif p.c.connected:
			steer = clampf(p.c.roll() / Rules.FULL_TILT, -1.0, 1.0)
		s.x = clampf(s.x + steer * Rules.SPEED * delta, -Rules.HALF_RANGE, Rules.HALF_RANGE)
		var on := absf(s.x - goal) <= Rules.TARGET_WIDTH * 0.5
		s.bonus = s.bonus + delta if on else 0.0
		p.score += Rules.points(on, s.bonus, delta)
		_place(p, phase_time)
	if phase_time >= Rules.ROUND_SECONDS:
		finish_round()


func _draw_hud(h: PlayerHud, p: Player, k: float) -> void:
	Hud.draw(self, h, p, k)


func _draw_overlay(o: Overlay, k: float) -> void:
	if phase == Phase.PLAY:
		draw_clock(o, Rules.ROUND_SECONDS - phase_time, k)
'''

RULES_GD = '''extends RefCounted
## Scoring rules of {id} (tools/new_game.py placeholder). Pure functions, so test_{id}.gd can
## check them without a scene. Distances in metres along the player's lane, time in seconds.

const ROUND_SECONDS := 30.0
const SPEED := 6.0               ## block speed at full tilt, m/s
const FULL_TILT := 0.6           ## rad of roll for full speed
const HALF_RANGE := 2.4          ## the block stays within +-HALF_RANGE of the lane centre
const TARGET_WIDTH := 1.2
const POINTS_PER_SECOND := 100.0
const STREAK_SECONDS := 3.0      ## on target this long doubles the points


static func target_x(t: float, slot: int) -> float:
	## The target's offset from the lane centre at time t (each slot has its own phase).
	return sin(t * 0.9 + slot * 1.3) * (HALF_RANGE - TARGET_WIDTH * 0.5)


static func points(on_target: bool, streak: float, delta: float) -> int:
	if not on_target:
		return 0
	var rate := POINTS_PER_SECOND * (2.0 if streak >= STREAK_SECONDS else 1.0)
	return roundi(rate * delta)
'''

HUD_GD = '''extends RefCounted
## HUD of {id} (tools/new_game.py placeholder), drawn into each player's split-screen cell.
## RSPartyGame already draws the name and score; add the game's own gauges here.


static func draw(game: RSPartyGame, h: Control, p: RSPartyGame.Player, k: float) -> void:
	if game.phase != RSPartyGame.Phase.PLAY:
		return
	var streak: float = p.data.bonus
	if streak > 0.0:
		game.draw_pill(h, "x2" if streak >= 3.0 else "+", Vector2(h.size.x * 0.5, h.size.y - 60 * k), 22 * k)
'''

