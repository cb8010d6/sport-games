def files(game_id: str) -> dict[Path, str]:
    folder = GAME / "scenes" / game_id
    return {folder / f"{game_id}_game.gd": GAME_GD, folder / f"{game_id}_game.tscn": SCENE_TSCN,
            folder / f"{game_id}_rules.gd": RULES_GD, folder / f"{game_id}_hud.gd": HUD_GD,
            folder / f"{game_id}_module.tres": MODULE_TRES,
            GAME / "tests" / f"test_{game_id}.gd": TEST_GD, GAME / "tests" / f"test_{game_id}.tscn": TEST_TSCN}


def english_entries(name: str, en: str) -> dict[str, str]:
    return {name: en, DESC: DESC_EN}


def append_english(entries: dict[str, str]) -> None:
    """Append missing keys to en.json as text, keeping the existing lines untouched."""
    current = json.loads(EN.read_text(encoding="utf-8"))
    new = {key: value for key, value in entries.items() if key not in current}
    if not new:
        return
    text = EN.read_text(encoding="utf-8").rstrip()
    lines = "".join(f",\n  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}" for k, v in new.items())
    EN.write_text(text[:-1].rstrip() + lines + "\n}\n", encoding="utf-8", newline="\n")


def remove_english(keys: list[str]) -> None:
    text = EN.read_text(encoding="utf-8")
    for key in keys:
        text = re.sub(r",\n\s*" + re.escape(json.dumps(key, ensure_ascii=False)) + r": \"(?:[^\"\\]|\\.)*\"(?=,?\n)", "", text)
    json.loads(text)   # still valid
    EN.write_text(text, encoding="utf-8", newline="\n")


def create(game_id: str, name: str, en: str) -> list[Path]:
    folder = GAME / "scenes" / game_id
    if folder.exists():
        raise SystemExit(f"{folder.relative_to(ROOT).as_posix()} already exists")
    values = {"id": game_id, "name": name, "oled": game_id.upper()[:10], "desc": DESC, "upper": game_id.upper(),
              "node": "".join(part.title() for part in game_id.split("_"))}
    folder.mkdir(parents=True)
    written = []
    for path, template in files(game_id).items():
        path.write_text(template.format(**values), encoding="utf-8", newline="\n")
        written.append(path)
    append_english(english_entries(name, en))
    return written


def remove(game_id: str) -> None:
    folder = GAME / "scenes" / game_id
    manifest = folder / f"{game_id}_module.tres"
    if not manifest.is_file() or "generated by tools/new_game.py" not in (folder / f"{game_id}_game.gd").read_text(encoding="utf-8"):
        raise SystemExit(f"{game_id} was not created by this scaffold; remove it by hand")
    name = re.search(r'(?m)^name = "(.*)"$', manifest.read_text(encoding="utf-8")).group(1)
    shutil.rmtree(folder)
    for path in (GAME / "tests").glob(f"test_{game_id}.*"):
        path.unlink()
    shared = json.dumps([p.read_text(encoding="utf-8") for p in (GAME / "scenes").glob("*/*_module.tres")], ensure_ascii=False)
    remove_english([key for key in english_entries(name, "") if json.dumps(key, ensure_ascii=False)[1:-1] not in shared])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("id", help="folder name and stable save ID: lower case letters, digits, _")
    parser.add_argument("--name", help="Chinese title (translation key)")
    parser.add_argument("--en", help="English title for game/i18n/en.json")
    parser.add_argument("--remove", action="store_true", help="delete a scaffold created by this tool")
    args = parser.parse_args(argv)
    if not ID.fullmatch(args.id):
        parser.error("id must be 2-20 characters: a-z first, then a-z, 0-9 or _")
    if args.remove:
        remove(args.id)
        print(f"Removed {args.id}")
        return 0
    if not args.name or not args.en:
        parser.error("--name and --en are required")
    for path in create(args.id, args.name, args.en):
        print("created", path.relative_to(ROOT).as_posix())
    print(f"next: godot --headless --path game --import; then -- --game={args.id} --demo=2 (see docs/NEW_GAME.md)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
